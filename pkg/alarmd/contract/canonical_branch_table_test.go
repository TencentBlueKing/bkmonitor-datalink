// canonicalBranchExpectation pins what one branch does today. Accepted output
// is stored as hex rather than as the bytes themselves: two earlier revisions
// of these tests wrote escape sequences literally and a tool folded them into
// the characters they denote, once splitting a string literal across lines and
// once putting a raw NUL in the source. Neither failed loudly. Hex cannot be
// folded into anything.
// The rejection text is hex for the same reason, and the reason is not
// hypothetical: the duplicate-field message echoes the offending key verbatim,
// so a rejection string can carry any bytes the input carried. Generating one
// of those as a JSON string literal emitted the astral character as a
// surrogate pair - correct JSON, and not compilable Go, which wants a single
// eight-digit escape and rejects lone surrogate halves. The build caught that
// one. Hex has one meaning in every language that reads this file, so nothing
// downstream has to agree about escapes.
type canonicalBranchExpectation struct {
	accept       bool
	wantHex      string
	wantErrorHex string
}

