// TestCanonicalBranchTableIsReachableAndPinned does two jobs at once.
//
// Reachability: every branch in the denominator has an input that reaches it,
// and running that input produces the stated result. A branch that cannot be
// reached is removed rather than left to make coverage permanently short.
//
// Pinning: the stated result is the behaviour a replacement has to reproduce
// byte for byte. This test is what turns the table from a list of intentions
// into a check.
func TestCanonicalBranchTableIsReachableAndPinned(t *testing.T) {
	probes := canonicalBranchProbes()
	if len(probes) != len(canonicalBranchExpectations) {
		t.Fatalf("%d probes against %d expectations; the denominator and the table have drifted apart",
			len(probes), len(canonicalBranchExpectations))
	}
	seen := make(map[string]bool, len(probes))
	for _, probe := range probes {
		if seen[probe.name] {
			t.Fatalf("branch %q appears twice; two branches sharing a name cannot both be counted as covered", probe.name)
		}
		seen[probe.name] = true
		want, ok := canonicalBranchExpectations[probe.name]
		if !ok {
			t.Fatalf("branch %q has no expectation; an unpinned branch is not part of the denominator", probe.name)
		}
		t.Run(probe.name, func(t *testing.T) {
			out, err := CanonicalJSONV2(probe.value)
			if want.accept {
				if err != nil {
					t.Fatalf("want accept, got error %v", err)
				}
				if got := hex.EncodeToString(out); got != want.wantHex {
					t.Fatalf("canonical bytes moved:\n want %s\n got  %s", want.wantHex, got)
				}
				return
			}
			wantError, decodeErr := hex.DecodeString(want.wantErrorHex)
			if decodeErr != nil {
				t.Fatalf("expectation is not hex: %v", decodeErr)
			}
			if err == nil {
				t.Fatalf("want rejection %q, got accept %s", wantError, hex.EncodeToString(out))
			}
			if err.Error() != string(wantError) {
				t.Fatalf("rejection text moved:\n want %q\n got  %q", wantError, err.Error())
			}
		})
	}
}
