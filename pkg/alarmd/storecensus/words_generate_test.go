// keyShaped is a string literal that can be a key or a piece of one: no
// spaces, only the characters keys and their format verbs are made of.
var keyShaped = regexp.MustCompile(`^[%a-zA-Z0-9_:.\-]+$`)

// literalWords is every word of the process's own key-shaped string
// literals, outside its tests: the words its keys are built from, and so the
// only words of a key it wrote that are not data.
func literalWords(t *testing.T, root string) []string {
	t.Helper()
	words := map[string]struct{}{}
	err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") ||
			strings.HasPrefix(entry.Name(), "words_") {
			return nil
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
		if err != nil {
			return err
		}
		ast.Inspect(file, func(node ast.Node) bool {
			literal, ok := node.(*ast.BasicLit)
			if !ok || literal.Kind != token.STRING {
				return true
			}
			value, err := strconv.Unquote(literal.Value)
			if err != nil || len(value) > 80 || !keyShaped.MatchString(value) {
				return true
			}
			for _, word := range wordsOf(value) {
				words[word] = struct{}{}
			}
			return true
		})
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	sorted := make([]string, 0, len(words))
	for word := range words {
		sorted = append(sorted, word)
	}
	sort.Strings(sorted)
	return sorted
}

// The process's own words are generated from its source: with
// ALARMD_REGENERATE_CENSUS_WORDS=1 this writes words_alarmd.go from every
// key-shaped literal under pkg/alarmd. Without it, it checks that the words
// the process's key builders are called with are known: a word missing only
// names its keys' families "*", and this keeps that from going unnoticed for
// the words the process writes most.
func TestTheProcesssOwnWordsAreItsLiterals(t *testing.T) {
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("ALARMD_REGENERATE_CENSUS_WORDS") == "1" {
		var source bytes.Buffer
		source.WriteString(licenseHeader)
		source.WriteString("\n// Code generated by TestTheProcesssOwnWordsAreItsLiterals with ALARMD_REGENERATE_CENSUS_WORDS=1. DO NOT EDIT.\n\n")
		source.WriteString("package storecensus\n\n// alarmdWords is every word of alarmd's key-shaped string literals.\nvar alarmdWords = []string{\n")
		for _, word := range literalWords(t, root) {
			fmt.Fprintf(&source, "\t%q,\n", word)
		}
		source.WriteString("}\n")
		formatted, err := format.Source(source.Bytes())
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile("words_alarmd.go", formatted, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	known := map[string]struct{}{}
	for _, word := range alarmdWords {
		known[word] = struct{}{}
	}
	for _, word := range []string{"alarmd", "runtime3", "gap", "ownership", "qgobj", "outctx", "schedule", "timeline",
		"activation", "manifest", "publication", "progress", "worker", "session", "grant"} {
		if _, ok := known[word]; !ok {
			t.Errorf("%q is not among the process's words; regenerate words_alarmd.go", word)
		}
	}
	if !sort.StringsAreSorted(alarmdWords) || !sort.StringsAreSorted(platformWords) {
		t.Error("a word list is not sorted")
	}
}

